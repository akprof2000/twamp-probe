//go:build linux

// Сверка пула портов пробы с эфемерным диапазоном ядра.
//
// Пул раздаёт номера сам и считает свободным всё, чего не выдавал. Если его
// диапазон перекрывается с net.ipv4.ip_local_port_range, ядро выдаёт те же
// номера чужим UDP-сокетам машины — и «свободный» по мнению пула порт
// оказывается занят. Замер получает «address already in use», порт уходит
// в карантин, замер повторяется с другим номером.
//
// Само по себе перекрытие — не ошибка: в поставляемых настройках диапазоны
// совмещены намеренно, иначе управляющим соединениям twping (они идут по TCP
// из того же диапазона) досталось бы куда меньше номеров, чем замеров. Поэтому
// проба не запрещает такую настройку, а называет её в журнале: если карантин
// начнёт расти, будет видно, откуда это.
package main

import (
	"fmt"
	"os"
	"strings"
)

// checkPortRangeOverlap описывает, как пул соотносится с эфемерным диапазоном
// ядра. Пустая строка означает, что говорить не о чем: диапазоны разведены
// либо прочитать настройку ядра не удалось.
func checkPortRangeOverlap(from, to int) string {
	if from <= 0 {
		return "" // пул выключен — порты и так выбирает ядро
	}

	low, high := ephemeralRange()
	if low <= 0 || high < low {
		return "" // прочитать не удалось — догадки хуже молчания
	}
	if to < low || from > high {
		return ""
	}
	return fmt.Sprintf(
		"пул портов пробы %d-%d перекрывается с эфемерным диапазоном ядра %d-%d. "+
			"Так и задумано в поставляемых настройках: из этого же диапазона ядро "+
			"берёт исходящие TCP-соединения, а управляющий канал twping нужен каждому "+
			"замеру TWamp. Плата — редкие коллизии по UDP с чужими сокетами машины "+
			"(чаще всего резолвер DNS): такой порт уходит в карантин, а замер "+
			"повторяется с другим номером. Если «в карантине» в состоянии пробы "+
			"устойчиво растёт, разведите диапазоны: ядру нижний участок "+
			"(sysctl net.ipv4.ip_local_port_range), пулу — всё выше (Probe:PortRange)",
		from, to, low, high)
}

// ephemeralRange читает net.ipv4.ip_local_port_range (0, 0 — прочитать не удалось).
func ephemeralRange() (int, int) {
	data, err := os.ReadFile("/proc/sys/net/ipv4/ip_local_port_range")
	if err != nil {
		return 0, 0
	}

	var low, high int
	if _, err := fmt.Sscan(strings.TrimSpace(string(data)), &low, &high); err != nil {
		return 0, 0
	}
	return low, high
}
