// Подготовка системных лимитов под настроенное число одновременных замеров.
//
// Число замеров задаёт **только** настройка Probe:MaxParallel — проба его не
// урезает. Подгонять потолок под лимиты ОС значит молча работать вполсилы,
// а внятный отказ ядра виден сразу и правится настройкой системы за минуту.
//
// Что проба делает вместо урезания:
//   - поднимает мягкий лимит процессов до жёсткого — это её собственный лимит,
//     и поднять его, кроме неё, некому;
//   - поднимает предел потоков Go: по умолчанию он равен 10000, и без этого
//     настройка выше упёрлась бы в него раньше, чем в возможности машины;
//   - предупреждает в журнале, если система к настроенному числу явно не
//     готова, — но работает с тем значением, которое задано.
//
// Ключевой факт для оценок: один замер **внешней утилитой** стоит ядру двух
// учётных единиц — процесса зонда и потока, который ждёт его в cmd.Wait()
// (замер: на 1500 зондов у пробы 1523 потока). Встроенные зонды не стоят ни
// процесса, ни потока — на них эти лимиты не распространяются.
package main

import "runtime/debug"

// unitsPerRun — во что обходится ядру один внешний замер: процесс + поток.
const unitsPerRun = 2

// goThreadHeadroom — запас потоков сверх настроенного числа замеров: сборщик
// мусора, сеть, журнал, HTTP-сервер.
const goThreadHeadroom = 1000

// prepareLimits настраивает систему под нужное число одновременных замеров.
// Возвращает предупреждение, если система к нему явно не готова (пустая строка —
// всё в порядке). Настроенное значение не меняется ни при каких условиях.
func prepareLimits(maxParallel int) string {
	// Предел потоков Go — единственная граница, которую проба сдвигает сама.
	// По умолчанию 10000: при большем числе замеров процесс умирает с
	// «programm exceeds N-thread limit», хотя ядро ещё позволяет.
	debug.SetMaxThreads(maxParallel*unitsPerRun + goThreadHeadroom)

	return checkSystemLimits(maxParallel)
}
