// Общие границы одновременных запусков, не зависящие от системы.
//
// Ключевой факт: один идущий замер стоит ядру двух учётных единиц — дочернего
// процесса зонда и потока пробы, который ждёт его в cmd.Wait(). Замер это
// подтверждает: на 1500 запущенных зондов у пробы 1523 потока. Отсюда и берутся
// обе границы ниже.
package main

// goThreadBudget — сколько потоков проба оставляет себе из жёсткого лимита Go
// (10000). Запас отдан служебным потокам: сборщик мусора, сеть, журнал, HTTP.
const goThreadBudget = 8000

// nprocSafetyShare — какую долю лимита процессов ОС проба разрешает себе занять.
// Остальное — запас на всё, что работает на машине помимо неё (ssh, systemd,
// обслуживание): выесть лимит целиком значит лишить администратора входа.
const nprocSafetyShare = 0.8

// unitsPerRun — во что обходится ядру один зонд: процесс + поток ожидания.
const unitsPerRun = 2

// nprocRunCap переводит лимит процессов ОС (ulimit -u) в допустимое число
// одновременных зондов.
//
// Без этого расчёта типовая настройка CentOS/RHEL (ulimit -u = 4096) роняет
// пробу ровно на 2048 запусках: ядро отказывает в создании потока, а для Go
// это fatal error, которую нельзя перехватить — служба умирает целиком.
func nprocRunCap(nprocLimit int) int {
	if nprocLimit <= 0 {
		return 0
	}
	return int(float64(nprocLimit) * nprocSafetyShare / unitsPerRun)
}
